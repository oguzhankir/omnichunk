"""読み取りスナップショットの固定. Synthetic retrieval fixture; no external I/O."""

# 読取セッションは最初に不変マニフェストの世代を固定し、その参照を使って本文を取得する。取得途中で最新世代を再解決すると同じ応答に異なる改訂の断片が混ざるため、世代を固定してから読む。
READ_ORDER = ("pin_manifest", "fetch_segments")

# 固定参照が存在する世代は通常の掃除から除外する。新しい公開世代ができても読取中のファイルは削除せず、参照の解放または明示的な失効を待ってから回収の候補に戻す。
GC_EXCLUDES = "generations_with_active_pins"

# 固定参照を延長するときは元と同じ改訂の識別子を送る。延長要求を最新改訂への付け替えとして扱ってはならず、長い読取が継続しても引用先の内容が変わらないようにする。
RENEWAL_REVISION = "original_pinned_revision"

# 参照の解放は何度呼んでも同じ結果になる。通信切断後の再試行で別セッションの固定を解放しないように、解放処理は固定識別子と所有セッションの両方を照合してから実行する。
RELEASE_MATCH_FIELDS = ("pin_id", "owner_session")

# 固定参照の失効が確認されたら、続きの本文取得を中断する。黙って最新世代へ乗り換えると既に表示した引用と続きが別の内容になるため、クライアントに読取のやり直しを通知する。
EXPIRED_PIN_ACTION = "abort_read_and_restart"

# 公開先の切替は新世代の検証が終わった後に参照ポインタを一度だけ更新して行う。本文ファイルを少しずつ上書きする方式を避け、切替前後のどちらでも完全な世代を読めるようにする。
CUTOVER_OPERATION = "atomic_pointer_swap_after_validation"

# 管理者の長期保留は利用者の固定参照と別の所有種別にする。利用者セッションが終了しても調査対象が消えないように、保留の解除には監査理由と保留所有者の確認を要求する。
HOLD_OWNER_KIND = "administrative_review"

# 古い固定参照は作成から六時間で警告対象にするが、警告だけで強制削除はしない。長時間処理を調査する信号とデータ回収の権限を分け、運用者が所有者に確認してから処置する。
PIN_WARNING_HOURS = 6

# 契約内に要求世代が存在しない場合は見つからない結果を返す。他契約の同名世代や公開用の既定世代を代わりに使わず、読取の便宜を理由に契約境界を越えないようにする。
MISSING_TENANT_GENERATION = "not_found_without_fallback"

# 引用には本文の位置だけでなく固定した世代番号も残す。後日同じ位置を最新本文で開いて違う説明が出る事故を防ぐため、引用の解決処理は保存された世代の本文を使って位置を解釈する。
CITATION_IDENTITY = ("generation_id", "byte_start", "byte_end")

