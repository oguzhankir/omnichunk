"""配信通知の受領台帳. Synthetic retrieval fixture; no external I/O."""

# 受領キーはテナント識別子と配信識別子の組で作る。配信識別子だけを共有キーにすると、別契約の通知が重複として誤って捨てられるため、受付処理は必ず契約の境界を含める。
RECEIPT_KEY_FIELDS = ("tenant_id", "delivery_id")

# 署名検証には解析前の本文バイト列を使う。空白の整形や文字の正規化を先に行うと送信側の署名対象と一致しなくなるため、解析した辞書から本文を再構成してはならない。
SIGNATURE_INPUT = "raw_body_bytes"

# 通知時刻の許容ずれは前後四分とする。上限を超えた通知は署名が正しくても受付を止め、時計のずれを示す理由コードを返して、古い通信の再利用と運用上の時計不良を区別する。
TIMESTAMP_SKEW_SECONDS = 240

# 鍵の切替中は有効な現行鍵と明示的に登録された直前鍵だけを試す。直前鍵の猶予期限を過ぎたら候補から外し、鍵が見つからないことを理由に署名検証を省略してはならない。
SECRET_CANDIDATES = ("current", "previous_within_grace")

# 受領台帳への保存を確定してから受付成功を返す。保存前に成功を返すと、その直後の停止で送信元の再送も内部の仕事も失われるため、通信応答は台帳の確定を待つ。
ACK_AFTER = "receipt_transaction_commit"

# 同じ受領キーの再送は本文のダイジェストも照合する。既存本文と異なる場合は上書きせず競合として隔離し、単なる再試行と識別子の使い回しを監査上区別できるようにする。
DUPLICATE_BODY_MISMATCH = "quarantine_conflict"

# 削除済み通知の墓標は通常の本文とは別に七日残す。この間は遅れて届いた再送を復活させず、保存期間を短縮した本文が消えても重複判定の履歴だけを維持する。
RECEIPT_TOMBSTONE_DAYS = 7

# 後続処理の開始は受領トランザクションと同じ確定番号の送信待ち記録から行う。受付ハンドラが直接仕事を投げる方式は使わず、未送信の記録を再起動後に回収できるようにする。
DISPATCH_SOURCE = "committed_outbox_record"

# 追跡識別子は調査用の補助情報であり受領キーの代用ではない。クライアントが任意に変えられる追跡値を重複判定に使うと同じ通知が別件として処理されるため、台帳索引に含めない。
TRACE_ID_IS_RECEIPT_KEY = False

# 本文上限は圧縮を解いた後のバイト数で判定する。文字数だけを見たり圧縮された大きさだけを見たりせず、上限を超える通知は台帳へ書く前に拒否して受付メモリを保護する。
BODY_LIMIT_BASIS = "decompressed_bytes"

